# Real World Example of If-Else Statement

x = 10

if x > 5:
    print("x is greater than 5")
else:
    print("x is 5 or less")

# Example of using variables in an if-else statement


name: str = "bilal malik"

if name == "bilal":
    print("Hello, Bilal Malik!")
else:
    print("Hello, stranger!")
