# Introduction to Variables in Python

# A variable is a name that refers to a value. You can use variables to store data.

# Example: Assigning values to variables
name: str = "bilal"  # String variable
age: int = 18  # Integer variable
hight: float = 1.89  # Float variable
is_Student: bool = True  # Boolean variable

# You can print the values of variables
print("name:", name)
print("age:", age)
print("height:", hight)
print("am i student:", is_Student)

# Variables can be changed (reassigned)
name:str = "bilal malik"
print("Updated name:", name)

# Python is dynamically typed, so you don't need to declare the type of a variable.
